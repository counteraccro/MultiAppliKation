export function homophoneBelt(belt: BeltId): HomophoneBelt | undefined {
  return HOMOPHONES.find((b) => b.belt === belt);
}

/** Toutes les phrases d'une ceinture, avec leur famille (pour les boutons et l'astuce). */
export function beltSentences(belt: HomophoneBelt): { sentence: Sentence; group: Group }[] {
  return belt.groups.flatMap((group) => group.sentences.map((sentence) => ({ sentence, group })));
}
