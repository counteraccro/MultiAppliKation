// Ceintures d'homophones : les 11 ceintures du classeur (voir .ai/analyse/11-ceintures.md).
// Phrases des fiches « Je prépare la ceinture… » de Charivari à l'école (utilisées avec
// leur accord), relues et corrigées, complétées par les nôtres. Une faute ici apprendrait
// une faute à l'enfant : homophones.test.ts vérifie chaque phrase.
// Les identifiants (« blanche.12 ») servent de clés dans le profil : ne jamais les changer
// ni les réutiliser ; une nouvelle phrase prend le numéro suivant.

import type { BeltId } from './belts';

export interface Sentence {
  id: string;
  /** Les réponses entre accolades, en minuscules : « Le lion {est} un animal carnivore. » */
  text: string;
  /** Numéro de la fiche Charivari, ou absent pour une phrase écrite pour l'app. */
  fiche?: number;
}

/** Une famille de mots qui se confondent : les boutons d'une phrase sont ceux de sa famille. */
export interface Group {
  choices: readonly string[];
  /** Ce qu'est chaque mot, dans l'ordre des choix. */
  rules: readonly string[];
  /** Comment choisir, à montrer après une erreur. */
  tip: string;
  /** Exemples de la leçon, le mot entre accolades (mis en couleur). */
  examples: readonly string[];
  sentences: readonly Sentence[];
}

export interface HomophoneBelt {
  belt: BeltId;
  /** Ce que demande la ceinture, comme dans le classeur. */
  skill: string;
  /** « Objectif de fin de CM1 » dans le classeur. */
  goal?: 'CM1' | 'CM2';
  groups: readonly Group[];
}

/** [numéro, phrase, fiche Charivari] ; sans fiche : phrase écrite pour l'app. */
type Raw = readonly [number, string, number?];

function sentences(belt: BeltId, raw: readonly Raw[]): Sentence[] {
  return raw.map(([n, text, fiche]) => ({ id: `${belt}.${n}`, text, ...(fiche ? { fiche } : {}) }));
}

